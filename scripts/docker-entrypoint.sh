#!/bin/sh
# ---------------------------------------------------------------------------
# نقطهٔ ورود کانتینر: اول مهاجرت‌های پایگاه‌داده، بعد بالا آوردن سرویس.
#
# چرا اینجا و نه در بیلد: `npm run build` هم مهاجرت را صدا می‌زند، ولی بیلد
# جایی اجرا می‌شود که هنوز پایگاه‌داده‌ای وجود ندارد (`migrate-if-configured`
# در نبود DATABASE_URL از خیرش می‌گذرد). پس روی یک سرور تازه، سرویس بالا
# می‌آمد و چون جدولی ساخته نشده بود هر مسیر داده ۵۰۰ می‌داد.
#
# اگر مهاجرت شکست بخورد کانتینر بالا نمی‌آید. این عمدی است: سرویسی که
# اسکیمایش با کدش نمی‌خواند، بدتر از سرویسی است که اصلاً بالا نیامده.
# ---------------------------------------------------------------------------
set -e

echo "[entrypoint] اجرای مهاجرت‌های پایگاه‌داده..."
node node_modules/prisma/build/index.js migrate deploy

echo "[entrypoint] راه‌اندازی سرویس روی پورت ${PORT:-3000}"
exec node dist/server.cjs
